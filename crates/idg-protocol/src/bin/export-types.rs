use idg_protocol::{Command, ErrorCode, Payload, Request, Response, Snapshot};
use ts_rs::TS;

fn main() {
    let config = ts_rs::Config::default();
    let text = [
        Command::decl(&config),
        ErrorCode::decl(&config),
        Snapshot::decl(&config),
        Payload::decl(&config),
        Request::decl(&config),
        Response::decl(&config),
    ]
    .into_iter()
    .map(|line| format!("export {line}\n"))
    .collect::<String>();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/shared-types");
    std::fs::create_dir_all(&root).unwrap();
    std::fs::write(
        root.join("protocol.ts"),
        format!("// Generated by cargo run -p idg-protocol --bin export-types.\n{text}"),
    )
    .unwrap();
}
