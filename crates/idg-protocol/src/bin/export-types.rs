use idg_protocol::*;
use ts_rs::TS;

fn main() {
    let config = ts_rs::Config::default();
    let text = [
        RuleEffect::decl(&config),
        OrganizationRule::decl(&config),
        RulePreview::decl(&config),
        PowerAction::decl(&config),
        ScheduleState::decl(&config),
        QueueSchedule::decl(&config),
        DownloadQueue::decl(&config),
        OrganizationCommand::decl(&config),
        OrganizationState::decl(&config),
        StartPolicy::decl(&config),
        CreateDownload::decl(&config),
        AppPreferences::decl(&config),
        RequestMode::decl(&config),
        Priority::decl(&config),
        TransferOptions::decl(&config),
        ResourceLimits::decl(&config),
        RangeSnapshot::decl(&config),
        ResumeCapability::decl(&config),
        IntegrityState::decl(&config),
        ConflictPolicy::decl(&config),
        NewDownload::decl(&config),
        TransferState::decl(&config),
        DownloadError::decl(&config),
        UnavailableDownload::decl(&config),
        DownloadSnapshot::decl(&config),
        Command::decl(&config),
        ErrorCode::decl(&config),
        Snapshot::decl(&config),
        Payload::decl(&config),
        Request::decl(&config),
        Response::decl(&config),
        ConnectionState::decl(&config),
    ]
    .into_iter()
    .map(|line| {
        format!(
            "export {}\n",
            line.lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n")
        )
    })
    .collect::<String>();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/shared-types");
    std::fs::create_dir_all(&root).unwrap();
    std::fs::write(
        root.join("protocol.ts"),
        format!("// Generated by cargo run -p idg-protocol --bin export-types.\n{text}"),
    )
    .unwrap();
}
